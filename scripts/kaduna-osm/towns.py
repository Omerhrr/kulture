#!/usr/bin/env python3
"""Bake the other towns of Kaduna State into the same map format as the
Kaduna city bake (frontend/app/utils/kadunaBake.json).

The city bake came from OpenStreetMap. This sandbox has no network, so the
towns are authored from public geography: real town centres, the real
highways between them, the real landmarks and districts, at approximately
the right places (lat/lon -> local metres, 1 raw unit = 10 m). The street
grids, houses and trees are then generated by the game exactly like the
city's. Run `fetch_osm.py` with a town's bbox to replace a town with real
OSM data later; the output format is the same.

Usage:  python towns.py            # writes frontend/app/utils/towns/*.json
"""

from __future__ import annotations

import json
import math
import os
import random

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "frontend", "app", "utils", "towns")
BOUNDS = {"xmin": -1400, "xmax": 700, "zmin": -1020, "zmax": 1450}  # same as the city (server bounds)
PALETTES = {
    "wall": ["#c9b18a", "#b8a07a", "#d8c9a3", "#a89468", "#c96f4a", "#9c8a6a", "#e0d6bd", "#7a8c5a"],
    "roof": ["#b04a3a", "#8a8f96", "#6b7280", "#96524a", "#7d8a7a"],
}


def proj(origin, lat, lon):
    m_lon = 111_320.0 * math.cos(math.radians(origin[0]))
    m_lat = 110_574.0
    return [round((lon - origin[1]) * m_lon / 10.0, 1), round(-(lat - origin[0]) * m_lat / 10.0, 1)]


def line(origin, pts):
    return [proj(origin, a, b) for a, b in pts]


def densify_line(pts, step=20.0):
    out = [pts[0]]
    for (ax, az), (bx, bz) in zip(pts, pts[1:]):
        n = max(1, int(math.hypot(bx - ax, bz - az) / step))
        for k in range(1, n + 1):
            out.append([round(ax + (bx - ax) * k / n, 1), round(az + (bz - az) * k / n, 1)])
    return out


def clip_ok(p, pad=0):
    return BOUNDS["xmin"] - pad <= p[0] <= BOUNDS["xmax"] + pad and BOUNDS["zmin"] - pad <= p[1] <= BOUNDS["zmax"] + pad


def bridges_for(roads, river):
    # bridges where a named road crosses the river
    bridges = []
    if river["main"]:
        for r in roads:
            if not r["name"]:
                continue
            for p in r["pts"][::2]:
                d = min(math.hypot(p[0] - q[0], p[1] - q[1]) for q in river["main"])
                if d < river["width"] * 0.6:
                    i = r["pts"].index(p)
                    q2 = r["pts"][min(i + 1, len(r["pts"]) - 1)]
                    bridges.append({"name": r["name"], "x": p[0], "z": p[1], "rot": round(math.atan2(q2[0] - p[0], q2[1] - p[1]), 3), "w": 3.2})
                    break
    return bridges


RAW = os.path.join(os.path.dirname(os.path.abspath(__file__)), "raw")
CLS = {"motorway": "trunk", "trunk": "trunk", "primary": "primary", "secondary": "secondary", "tertiary": "secondary"}
KIND = [("marketplace", "market"), ("place_of_worship", None), ("hospital", "hospital"), ("university", "campus"), ("college", "campus"), ("bus_station", "motorpark"), ("station", "station"), ("stadium", "stadium"), ("park", "park"), ("townhall", "govhouse")]


def osm(town, name):
    p = os.path.join(RAW, town, f"{name}.json")
    return json.load(open(p))["elements"] if os.path.exists(p) else None


def osm_overlay(t, b):
    """Replace the authored geometry with real OpenStreetMap data when the
    raw download for this town exists (fetch_towns.py)."""
    o = t["origin"]
    roads = osm(t["id"], "roads")
    if not roads:
        return b
    out = []
    for w in roads:
        g = w.get("geometry")
        if not g:
            continue
        hw = w["tags"].get("highway", "")
        pts = [proj(o, p["lat"], p["lon"]) for p in g]
        pts = [p for p in pts if clip_ok(p, 100)]
        if len(pts) >= 2:
            out.append({"name": w["tags"].get("name", ""), "class": CLS.get(hw, "residential"), "pts": pts})
    b["roads"] = out
    b["meta"]["realStreets"] = True
    b["meta"]["attribution"] = "Map data (c) OpenStreetMap contributors, ODbL. Stylized game geometry."
    rivers = osm(t["id"], "river") or []
    mains = [w for w in rivers if w["tags"].get("waterway") == "river" and w.get("geometry")]
    if mains:
        longest = max(mains, key=lambda w: len(w["geometry"]))
        b["river"]["main"] = densify_line([proj(o, p["lat"], p["lon"]) for p in longest["geometry"]], 25)
        b["river"]["side"] = [densify_line([proj(o, p["lat"], p["lon"]) for p in w["geometry"]], 25) for w in rivers if w is not longest and w.get("geometry") and len(w["geometry"]) > 3][:12]
    rail = osm(t["id"], "rail") or []
    if rail:
        b["rail"] = [[proj(o, p["lat"], p["lon"]) for p in w["geometry"]] for w in rail if w.get("geometry")]
    blds = osm(t["id"], "buildings") or []
    if blds:
        rnd = random.Random(t["seed"] + 1)
        houses = []
        for e in blds:
            c = e.get("center")
            if not c:
                continue
            x, z = proj(o, c["lat"], c["lon"])
            if clip_ok([x, z]):
                houses.append([x, z, round(8 + rnd.random() * 6, 1), round(6 + rnd.random() * 4, 1), round((rnd.random() - 0.5) * 0.3, 3), rnd.randrange(8), rnd.randrange(5)])
        # the game adds compounds around every sampled house: thin dense towns
        step = max(1, len(houses) // 9000)
        b["houses"] = houses[::step]
    places = osm(t["id"], "places") or []
    if places:
        b["places"] = [{"name": p["tags"].get("name", ""), "x": proj(o, p["lat"], p["lon"])[0], "z": proj(o, p["lat"], p["lon"])[1]} for p in places if p.get("tags", {}).get("name")][:30]
    # extra named landmarks from OSM that aren't near a curated one
    lms = osm(t["id"], "landmarks") or []
    have = [(l["x"], l["z"]) for l in b["landmarks"]]
    n = 0
    for e in lms:
        tags = e.get("tags", {})
        c = e.get("center") or ({"lat": e["lat"], "lon": e["lon"]} if "lat" in e else None)
        if not c or not tags.get("name"):
            continue
        kind = None
        for k, v in KIND:
            if k in tags.values():
                kind = v or ("mosque" if tags.get("religion") == "muslim" else "cathedral" if tags.get("religion") == "christian" else None)
        if not kind:
            continue
        x, z = proj(o, c["lat"], c["lon"])
        if not clip_ok([x, z]) or any(math.hypot(x - a, z - bb) < 25 for a, bb in have):
            continue
        size = {"market": (90, 60, 18), "mosque": (40, 34, 20), "cathedral": (30, 40, 20), "hospital": (60, 45, 16), "campus": (90, 70, 18), "motorpark": (60, 44, 14), "station": (100, 50, 18), "stadium": (90, 70, 24), "park": (50, 36, 14), "govhouse": (60, 45, 16)}[kind]
        b["landmarks"].append({"key": f"osm_{e['id']}", "name": tags["name"], "x": x, "z": z, "kind": kind, "kw": size[0], "kd": size[1], "lh": size[2]})
        have.append((x, z))
        n += 1
        if n >= 40:
            break
    b["bridges"] = bridges_for(b["roads"], b["river"])
    return b


def build(t):
    o = t["origin"]
    rnd = random.Random(t["seed"])
    roads = []
    for name, cls, pts in t["roads"]:
        pl = densify_line(line(o, pts))
        pl = [p for p in pl if clip_ok(p, 200)]
        if len(pl) >= 2:
            roads.append({"name": name, "class": cls, "pts": pl})
    river = {"main": [], "width": 10, "side": []}
    if t.get("river"):
        river = {"main": densify_line(line(o, t["river"]["pts"]), 25), "width": t["river"]["width"], "side": [densify_line(line(o, s), 25) for s in t["river"].get("side", [])]}
    rail = [densify_line(line(o, r), 30) for r in t.get("rail", [])]
    airport = {"runway": None, "apron": None}
    if t.get("runway"):
        rw = line(o, t["runway"])
        airport["runway"] = densify_line(rw, 15)
        mx = (rw[0][0] + rw[-1][0]) / 2
        mz = (rw[0][1] + rw[-1][1]) / 2
        airport["apron"] = {"x": mx + 12, "z": mz + 10, "w": 50, "d": 30}
    landmarks = []
    for key, name, lat, lon, kind, kw, kd, lh in t["landmarks"]:
        x, z = proj(o, lat, lon)
        landmarks.append({"key": key, "name": name, "x": x, "z": z, "kind": kind, "kw": kw, "kd": kd, "lh": lh})
    places = []
    houses = []
    trees = []
    for name, lat, lon, radius_m, density in t["districts"]:
        cx, cz = proj(o, lat, lon)
        places.append({"name": name, "x": cx, "z": cz})
        r_raw = radius_m / 10.0
        n = int(density * 0.3 * (radius_m / 100.0) ** 2)
        for _ in range(n):
            a = rnd.random() * math.tau
            d = r_raw * math.sqrt(rnd.random())
            x = cx + math.cos(a) * d
            z = cz + math.sin(a) * d
            if not clip_ok([x, z]):
                continue
            houses.append([round(x, 1), round(z, 1), round(8 + rnd.random() * 6, 1), round(6 + rnd.random() * 4, 1), round((rnd.random() - 0.5) * 0.3, 3), rnd.randrange(8), rnd.randrange(5)])
    for _ in range(t.get("trees", 500)):
        x = rnd.uniform(BOUNDS["xmin"], BOUNDS["xmax"])
        z = rnd.uniform(BOUNDS["zmin"], BOUNDS["zmax"])
        trees.append([round(x, 1), round(z, 1), round(0.8 + rnd.random() * 0.6, 2)])
    bridges = bridges_for(roads, river)
    return {
        "meta": {
            "attribution": "Town layout authored from public geography (real centres, highways, landmarks; approximate). Street grid and houses are generated. Replaceable with OpenStreetMap data (ODbL).",
            "origin": list(o),
            "unitM": 10,
            "bounds": BOUNDS,
            "region": t["id"],
            "name": t["name"],
        },
        "river": river,
        "roads": roads,
        "rail": rail,
        "airport": airport,
        "landmarks": landmarks,
        "places": places,
        "bridges": bridges,
        "houses": houses,
        "housePalettes": PALETTES,
        "trees": trees,
    }


